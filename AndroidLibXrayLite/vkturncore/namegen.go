func generateName() string {
	isFemale := rand.Intn(2) == 1
	var first, last string

	if isFemale {
		first = femaleFirstNames[rand.Intn(len(femaleFirstNames))]
		rawLast := lastNames[rand.Intn(len(lastNames))]
		if strings.HasSuffix(rawLast, "ов") || strings.HasSuffix(rawLast, "ев") || strings.HasSuffix(rawLast, "ин") {
			last = rawLast + "а"
		} else if strings.HasSuffix(rawLast, "ий") || strings.HasSuffix(rawLast, "ый") {
			last = strings.TrimSuffix(strings.TrimSuffix(rawLast, "ий"), "ый") + "ая"
		} else {
			last = rawLast
		}
	} else {
		first = maleFirstNames[rand.Intn(len(maleFirstNames))]
		last = lastNames[rand.Intn(len(lastNames))]
	}

	return fmt.Sprintf("%s %s", first, last)
}
